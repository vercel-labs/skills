#!/usr/bin/env bash
# Bundles everything the database needs into ONE file you can paste into a hosted
# database's SQL editor (Neon, Supabase): deploy/setup.sql. Re-run after adding a migration.
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "-- Society Kitchen: complete database setup. Paste into your SQL editor and run ONCE on an empty database."
  echo "-- Generated by scripts/build-setup-sql.sh. Contains no demo data."
  echo; echo "-- == roles =="; cat supabase/dev_roles.sql
  echo; echo "-- the login this app connects as must be allowed to act as the 'authenticated' role"
  echo "grant authenticated to current_user;"
  for f in supabase/migrations/*.sql; do echo; echo "-- == $(basename "$f") =="; cat "$f"; done
} > deploy/setup.sql
echo "Wrote deploy/setup.sql ($(wc -l < deploy/setup.sql) lines)"
